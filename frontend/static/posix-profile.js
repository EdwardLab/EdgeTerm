function procStatus({ command, memoryBytes }) {
  const name = String(command || "ash").split(/[\s/]/).filter(Boolean).pop() || "ash";
  const memoryKiB = kibibytes(memoryBytes);
  return [
    `Name:\t${name.slice(0, 15)}`,
    "State:\tR (running)",
    "Tgid:\t1",
    "Ngid:\t0",
    "Pid:\t1",
    "PPid:\t0",
    "TracerPid:\t0",
    "Uid:\t1000\t1000\t1000\t1000",
    "Gid:\t1000\t1000\t1000\t1000",
    "FDSize:\t64",
    `VmPeak:\t${memoryKiB} kB`,
    `VmSize:\t${memoryKiB} kB`,
    "Threads:\t1",
    "SigQ:\t0/0",
    "Cpus_allowed:\t1",
    "Cpus_allowed_list:\t0",
    "voluntary_ctxt_switches:\t0",
    "nonvoluntary_ctxt_switches:\t0",
    "",
  ].join("\n");
}

